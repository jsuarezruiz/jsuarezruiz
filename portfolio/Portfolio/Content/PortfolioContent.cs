using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Text.Json.Serialization;
using Avalonia.Platform;

namespace Portfolio.Content;

public sealed class Profile
{
    public string Name { get; set; } = "";
    public string Login { get; set; } = "";
    public string Bio { get; set; } = "";
    public string Location { get; set; } = "";
    public int Followers { get; set; }
    public int Repos { get; set; }
    public int Stars { get; set; }
    public string Url { get; set; } = "";
}

public sealed class Era
{
    public string Id { get; set; } = "";
    public string Name { get; set; } = "";
    public string Years { get; set; } = "";
}

public sealed class Link
{
    public string Label { get; set; } = "";
    public string Url { get; set; } = "";
}

public sealed class PhoneApp
{
    public string Name { get; set; } = "";
    public string Url { get; set; } = "";
}

public sealed class Photo
{
    public string File { get; set; } = "";
    public string Caption { get; set; } = "";
}

public sealed class Job
{
    public string Company { get; set; } = "";
    public string Role { get; set; } = "";
    public string Period { get; set; } = "";
    public List<string> Points { get; set; } = new();
}

public sealed class Resume
{
    public string Title { get; set; } = "";
    public string Summary { get; set; } = "";
    public string Pdf { get; set; } = "";
    public List<Job> Experience { get; set; } = new();
    public List<string> OpenSource { get; set; } = new();
    public List<string> Achievements { get; set; } = new();
    public List<string> Communities { get; set; } = new();
    public List<string> Education { get; set; } = new();
    public List<string> Skills { get; set; } = new();
    public List<string> Languages { get; set; } = new();
}

public sealed class Project
{
    public string Name { get; set; } = "";
    public string Era { get; set; } = "";
    public int Stars { get; set; }
    public string Description { get; set; } = "";
    public string Url { get; set; } = "";
}

public sealed class PortfolioContent
{
    private static PortfolioContent? s_current;

    public Profile Profile { get; set; } = new();
    public List<Era> Eras { get; set; } = new();
    public List<Link> Links { get; set; } = new();
    public List<PhoneApp> Apps { get; set; } = new();
    public List<Photo> Photos { get; set; } = new();
    public Resume Resume { get; set; } = new();
    public List<Project> Projects { get; set; } = new();

    /// <summary>
    /// The content generated by tools/UpdateContent.cs.
    /// </summary>
    public static PortfolioContent Current => s_current ??= Load();

    public IEnumerable<Project> ByEra(string era) => Projects.Where(p => p.Era == era);

    private static PortfolioContent Load()
    {
        using var stream = AssetLoader.Open(new Uri("avares://Portfolio/Assets/content.json"));
        return JsonSerializer.Deserialize(stream, ContentJsonContext.Default.PortfolioContent) ?? new PortfolioContent();
    }
}

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(PortfolioContent))]
internal sealed partial class ContentJsonContext : JsonSerializerContext
{
}
